template <>
__device__ __forceinline__ float wright_omega<float>(float x)
{
    // Non-finite guard
    if (!isfinite(x)) {
        if (x > 0.0f) return INFINITY; // +Inf
        if (x < 0.0f) return 0.0f;
        return x; // NaN
    }

    if (x < WO_F_X1) {                          // x < 0
        if (x < WO_F_X0) {
            float z = expf(x);
            return _wo_rat_t<float, 4, 3>(z, WO_F_P0, WO_F_Q0);
        } else {
            return _wo_rat_t<float, 4, 4>(x, WO_F_P1, WO_F_Q1);
        }
    }
    else if (x < WO_F_X2) {
        return _wo_rat_t<float, 4, 4>(x, WO_F_P2, WO_F_Q2);
    }
    else if (x < WO_F_X3) {
        return _wo_rat_t<float, 4, 4>(x, WO_F_P3, WO_F_Q3);
    }
    else if (x < WO_F_X4) {
        return _wo_rat_t<float, 4, 5>(x, WO_F_P4, WO_F_Q4);
    }
    else if (x < WO_F_X5) {
        return _wo_rat_t<float, 4, 4>(x, WO_F_P5, WO_F_Q5);
    }
    else if (x < WO_F_X6) {
        return _wo_rat_t<float, 4, 4>(x, WO_F_P6, WO_F_Q6);
    }
    else if (x < WO_F_X7) {
        return _wo_rat_t<float, 4, 4>(x, WO_F_P7, WO_F_Q7);
    }
    else {
        return x * (1.0f - logf(x) / (x + 1.0f));
    }
}

