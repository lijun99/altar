// ===========================================================================
//  Horner evaluation helpers  (coefficients in DESCENDING power order)
// ===========================================================================
template <typename T, int N>
__device__ __forceinline__ T _wo_horner(const T* c, T x)
{
    T r = c[0];
    #pragma unroll
    for (int i = 1; i < N; ++i)
        r = r * x + c[i];
    return r;
}

// We can't template on runtime np/nq easily, so just write it out:
template <typename T, int NP, int NQ>
__device__ __forceinline__ T _wo_rat_t(T x, const T* P, const T* Q)
{
    return _wo_horner<T, NP>(P, x) / _wo_horner<T, NQ>(Q, x);
}

